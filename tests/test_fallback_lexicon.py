"""Лексический разбор названия упражнения: мышца и оборудование.

Это путь по умолчанию (CLASSIFIER_MODE выключен), поэтому его качество —
не «запасной вариант», а то, что видит пользователь, нажимая «Определить
автоматически».

Корень прежних промахов был морфологический: словарь перечислял падежные формы
вручную и часть пропускал ("турник" есть, "турнике" нет; "гантелей" есть,
"гантелями" нет). Поэтому сопоставление идёт по основам слов, а не по точным
формам.
"""
import pytest

from api.services import equipment as equip
from api.services import exercise_classifier as clf


def _fallback(name: str):
    return clf._fallback(name)


# --- оборудование: падежи не должны ничего ломать ---------------------------

@pytest.mark.parametrize(
    "name, expected",
    [
        ("жим штанги лёжа", [equip.BARBELL]),
        ("приседания со штангой", [equip.BARBELL]),
        ("тяга штанги в наклоне", [equip.BARBELL]),
        ("сгибания на бицепс с гантелями", [equip.DUMBBELL]),
        ("жим гантелей сидя", [equip.DUMBBELL]),
        ("разведение гантели в стороны", [equip.DUMBBELL]),
        ("подтягивания на турнике", [equip.PULLUP_BAR]),
        ("отжимания на брусьях", [equip.DIP_BARS]),
        ("махи гирей", [equip.KETTLEBELL]),
        ("жим в машине Смита", [equip.SMITH]),
        ("тяга верхнего блока", [equip.BLOCK_MACHINE]),
        ("сведение рук в кроссовере", [equip.BLOCK_MACHINE]),
        ("разгибания в тренажёре", [equip.BLOCK_MACHINE]),
        ("отведение ноги с резинкой", [equip.BAND]),
        ("жим лёжа на скамье", [equip.BENCH]),
        ("отжимания от пола", []),
    ],
)
def test_equipment_survives_russian_cases(name, expected):
    assert _fallback(name)["equipment_needed"] == expected


def test_smith_beats_generic_machine():
    """'машина смита' должна разбираться раньше generic 'машина'."""
    assert _fallback("жим в машине Смита")["equipment_needed"] == [equip.SMITH]


def test_multiple_equipment_is_collected():
    got = _fallback("жим гантелей на наклонной скамье")["equipment_needed"]
    assert set(got) == {equip.DUMBBELL, equip.BENCH}


# --- мышцы ------------------------------------------------------------------

@pytest.mark.parametrize(
    "name, muscle",
    [
        # то, что ломалось раньше
        ("жим штанги лёжа", "Грудь"),
        ("французский жим", "Трицепс"),
        ("гиперэкстензия", "Поясница"),
        # грудь
        ("жим лёжа", "Грудь"),
        ("жим гантелей на наклонной скамье", "Грудь"),
        ("разведение гантелей лёжа", "Грудь"),
        ("отжимания от пола", "Грудь"),
        # спина
        ("подтягивания на турнике", "Широчайшие"),
        ("тяга верхнего блока", "Широчайшие"),
        ("тяга штанги в наклоне", "Средняя часть спины"),
        # Каталог относит становую к задней поверхности бедра, а не к пояснице.
        ("становая тяга", "Бицепсы ног"),
        # ноги
        ("приседания со штангой", "Квадрицепсы"),
        ("жим ногами", "Квадрицепсы"),
        ("разгибания ног сидя", "Квадрицепсы"),
        ("выпады с гантелями", "Квадрицепсы"),
        ("сгибания ног лёжа", "Бицепсы ног"),
        ("румынская тяга", "Бицепсы ног"),
        ("подъёмы на носки", "Икры"),
        ("ягодичный мостик", "Ягодицы"),
        # руки
        ("сгибания рук с гантелями", "Бицепс"),
        ("молотки с гантелями", "Бицепс"),
        ("разгибания рук на блоке", "Трицепс"),
        ("отжимания на брусьях", "Трицепс"),
        # плечи и трапеция
        ("махи гантелями в стороны", "Средняя дельта"),
        ("жим гантелей стоя", "Передняя дельта"),
        ("разведение гантелей в наклоне", "Задняя дельта"),
        ("шраги со штангой", "Трапеция"),
        # корпус
        ("скручивания на пресс", "Пресс"),
        ("планка", "Пресс"),
        ("подъём ног в висе", "Пресс"),
        # предплечья
        ("сгибания запястий", "Предплечья"),
    ],
)
def test_muscle_from_name(name, muscle):
    assert _fallback(name)["main_muscle_group"] == muscle


def test_muscle_values_are_from_catalog_vocabulary():
    """Фолбэк не должен изобретать названия, которых нет в каталоге."""
    known = {
        "Квадрицепсы", "Средняя дельта", "Пресс", "Грудь", "Бицепсы ног",
        "Трицепс", "Бицепс", "Широчайшие", "Средняя часть спины", "Икры",
        "Предплечья", "Ягодицы", "Поясница", "Трапеция", "Аддукторы",
        "Абдукторы", "Передняя дельта", "Задняя дельта",
    }
    for _, muscle in clf._FALLBACK_RULES:
        assert muscle in known, f"неизвестная мышца в правилах: {muscle}"


def test_unknown_name_degrades_quietly():
    r = _fallback("абракадабра")
    assert r["main_muscle_group"] is None
    assert r["equipment_needed"] == []
    assert r["source"] == "fallback"


def test_specific_rule_wins_over_generic():
    """'бицепс бедра' — про заднюю поверхность, а не про руку."""
    assert _fallback("сгибания бицепса бедра")["main_muscle_group"] == "Бицепсы ног"
    assert _fallback("сгибания на бицепс")["main_muscle_group"] == "Бицепс"
