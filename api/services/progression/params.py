# Допуск на ошибку обратной конвертации кг -> lb при округлении ВНИЗ к шагу
# в фунтах. Вес хранится в БД в килограммах с округлением до сотых, поэтому
# легитимная точка сетки в фунтах (например, 160 lb) при хранении теряет до
# 0.005 кг точности (round(..., 2)). Обратный перевод этой уже округлённой
# величины в фунты даёт число чуть МЕНЬШЕ исходного (например, 159.9946 lb
# вместо 160), и floor-деление на шаг съедает целый шаг: 160 -> 150 lb.
# 0.005 кг ~= 0.011 lb — допуск берём с запасом.
